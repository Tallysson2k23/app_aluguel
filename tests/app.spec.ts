import { expect, test, type Page } from '@playwright/test'

const marker = (page: Page, style: string) => page.locator('.leaflet-marker-icon .house-pin.' + style)
const nav = (page: Page, name: string) => page.getByRole('navigation', { name: 'Navegação principal' }).getByRole('link', { name, exact: true })
async function openFilters(page: Page) {
  await page.getByRole('button', { name: /^Filtros/ }).click()
  return page.getByRole('dialog')
}
async function showList(page: Page) {
  const toggle = page.getByRole('button', { name: 'Lista', exact: true })
  if (await toggle.isVisible()) await toggle.click()
}
test.beforeEach(async ({ page }) => {
  // Exercise tile failure without sending automated traffic to the public tile service.
  await page.route('https://tile.openstreetmap.org/**', route => route.abort())
})

test('mapa, legenda, prévia, lista, filtros e modo offline', async ({ page, context }) => {
  await page.addInitScript(() => {
    navigator.geolocation.getCurrentPosition = (_, fail) => fail?.({
      code: 1, message: 'Permissão negada no teste', PERMISSION_DENIED: 1, POSITION_UNAVAILABLE: 2, TIMEOUT: 3,
    })
  })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Encontre seu próximo lar.' })).toBeVisible()
  await expect(marker(page, 'rent').first()).toBeVisible()
  await expect(marker(page, 'soon').first()).toBeVisible()
  await expect(marker(page, 'sale').first()).toBeVisible()
  await expect(marker(page, 'occupied')).toHaveCount(0)
  const filters = await openFilters(page)
  await filters.getByLabel('Mostrar ocupados').check()
  await filters.getByRole('button', { name: 'Aplicar filtros' }).click()
  await expect(marker(page, 'occupied')).toHaveCount(1)
  await expect(page.getByText('Mapa base indisponível. Você pode continuar pela Lista.')).toBeVisible()
  await page.getByRole('button', { name: 'Minha localização' }).click()
  await expect(page.getByText('Não foi possível usar sua localização.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Buscar nesta área' }).click()
  await expect(marker(page, 'occupied')).toHaveCount(1)

  await page.getByRole('textbox', { name: 'Buscar por bairro ou título' }).fill('sao cristovao')
  await expect(marker(page, 'rent')).toHaveCount(0)
  const pin = page.locator('.leaflet-marker-icon[aria-label*="Apartamento com dois quartos"]')
  await pin.click()
  const preview = page.getByRole('region', { name: 'Prévia do imóvel' })
  await expect(preview.getByRole('heading', { name: 'Apartamento com dois quartos' })).toBeVisible()
  await expect(preview).toBeInViewport()
  await expect(preview.getByText('São Cristóvão')).toBeVisible()
  await preview.getByRole('link', { name: 'Ver detalhes' }).click()
  await expect(page.getByRole('heading', { name: 'Localização aproximada' })).toBeVisible()
  await expect(page.getByRole('button', { name: /WhatsApp|Tenho interesse/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Voltar para explorar' }).click()
  await expect(page.getByRole('textbox', { name: 'Buscar por bairro ou título' })).toHaveValue('sao cristovao')
  await page.getByRole('button', { name: 'Fechar prévia' }).click()
  await showList(page)
  await expect(page.getByRole('link', { name: 'Apartamento com dois quartos' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Casa térrea com varanda' })).toHaveCount(0)
  await context.setOffline(true)
  await expect(page.getByText('Você está offline.', { exact: false })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Apartamento com dois quartos' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
})

test('tela de 320 px com latência e espaço reduzido para digitação', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 568 })
  await page.route('http://127.0.0.1:8080/**', async route => {
    await new Promise(resolve => setTimeout(resolve, 750))
    await route.continue()
  })
  await page.goto('/')
  await expect(page.getByText('Buscando imóveis…', { exact: true })).toBeVisible()
  await expect(marker(page, 'rent').first()).toBeVisible()
  const filters = await openFilters(page)
  const neighborhood = filters.getByLabel('Bairro')
  await neighborhood.focus()
  await page.setViewportSize({ width: 320, height: 350 })
  await neighborhood.fill('Centro')
  await expect(neighborhood).toBeFocused()
  await filters.getByRole('button', { name: 'Aplicar filtros' }).click()
  await showList(page)
  await expect(page.getByRole('link', { name: 'Apartamento iluminado no Centro' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
})

